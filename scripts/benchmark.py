#!/usr/bin/env python3
"""Measure parsing, welding and topology-analysis cost across mesh sizes.

Reports measured values only. The hardware and software environment is
recorded alongside the results so that numbers are interpretable later and are
not mistaken for figures from a different machine.

    python scripts/benchmark.py
    python scripts/benchmark.py --json results.json --latex docs/generated/benchmark.tex
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import tempfile
import time
import tracemalloc
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from conftest import build_sphere  # noqa: E402  # type: ignore[import-not-found]
from relief_forge import read_stl, weld, write_stl  # noqa: E402
from relief_forge.topology import analyse_topology  # noqa: E402


@dataclass
class BenchmarkRow:
    """One measured configuration."""

    triangles: int
    file_size_mb: float
    parse_ms: float
    weld_ms: float
    topology_ms: float
    total_ms: float
    peak_memory_mb: float


def environment() -> dict[str, str]:
    """Record the machine and library versions these numbers came from."""
    return {
        "python": sys.version.split()[0],
        "numpy": np.__version__,
        "platform": platform.platform(),
        "machine": platform.machine(),
        "processor": platform.processor() or "unknown",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }


def _time(function, repeats: int):  # type: ignore[no-untyped-def]
    """Return the median wall-clock time in milliseconds and the last result."""
    samples: list[float] = []
    result = None
    for _ in range(repeats):
        started = time.perf_counter()
        result = function()
        samples.append((time.perf_counter() - started) * 1000.0)
    return statistics.median(samples), result


def benchmark(subdivisions: int, repeats: int) -> BenchmarkRow:
    """Time the full analysis path on a sphere at the given subdivision level."""
    triangles = build_sphere(radius=15.0, subdivisions=subdivisions)

    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "bench.stl"
        write_stl(path, triangles)
        size_mb = path.stat().st_size / (1024 * 1024)

        parse_ms, loaded = _time(lambda: read_stl(path), repeats)

        tracemalloc.start()
        weld_ms, welded = _time(lambda: weld(loaded), repeats)
        topology_ms, _ = _time(
            lambda: analyse_topology(welded.faces, len(welded.vertices)), repeats
        )
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()

    return BenchmarkRow(
        triangles=len(triangles),
        file_size_mb=round(size_mb, 3),
        parse_ms=round(parse_ms, 2),
        weld_ms=round(weld_ms, 2),
        topology_ms=round(topology_ms, 2),
        total_ms=round(parse_ms + weld_ms + topology_ms, 2),
        peak_memory_mb=round(peak / (1024 * 1024), 2),
    )


def to_latex(rows: list[BenchmarkRow], env: dict[str, str]) -> str:
    """Render measured rows as a booktabs table."""
    lines = [
        "% Generated by scripts/benchmark.py. Do not edit by hand.",
        "\\begin{tabular}{rrrrrrr}",
        "\\toprule",
        "Triangles & File (MB) & Parse (ms) & Weld (ms) & Topology (ms) "
        "& Total (ms) & Peak mem.\\ (MB) \\\\",
        "\\midrule",
    ]
    for row in rows:
        triangles = f"{row.triangles:,}".replace(",", "\\,")
        lines.append(
            f"{triangles} & {row.file_size_mb:.3f} & {row.parse_ms:.2f} & "
            f"{row.weld_ms:.2f} & {row.topology_ms:.2f} & {row.total_ms:.2f} & "
            f"{row.peak_memory_mb:.2f} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "",
        f"% environment: {env['platform']}, python {env['python']}, "
        f"numpy {env['numpy']}, measured {env['timestamp']}",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Benchmark geometry operations.")
    parser.add_argument(
        "--subdivisions", type=int, nargs="+", default=[3, 4, 5, 6],
        help="octahedron subdivision levels to measure",
    )
    parser.add_argument("--repeats", type=int, default=5, help="samples per measurement")
    parser.add_argument("--json", type=Path, help="write results as JSON")
    parser.add_argument("--latex", type=Path, help="write results as a LaTeX table")
    args = parser.parse_args()

    env = environment()
    print(f"platform : {env['platform']}")
    print(f"python   : {env['python']}   numpy {env['numpy']}")
    print(f"repeats  : {args.repeats} (median reported)\n")

    header = (
        f"{'triangles':>10}{'file MB':>10}{'parse ms':>10}"
        f"{'weld ms':>10}{'topo ms':>10}{'total ms':>10}{'peak MB':>10}"
    )
    print(header)
    print("-" * len(header))

    rows: list[BenchmarkRow] = []
    for level in args.subdivisions:
        row = benchmark(level, args.repeats)
        rows.append(row)
        print(
            f"{row.triangles:>10,}{row.file_size_mb:>10.3f}{row.parse_ms:>10.2f}"
            f"{row.weld_ms:>10.2f}{row.topology_ms:>10.2f}{row.total_ms:>10.2f}"
            f"{row.peak_memory_mb:>10.2f}"
        )

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(
            json.dumps({"environment": env, "results": [asdict(r) for r in rows]}, indent=2)
        )
        print(f"\nwrote {args.json}")

    if args.latex:
        args.latex.parent.mkdir(parents=True, exist_ok=True)
        args.latex.write_text(to_latex(rows, env))
        print(f"wrote {args.latex}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
